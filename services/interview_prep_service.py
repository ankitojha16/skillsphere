"""
SkillSphere Opportunity Hub — AI Interview Preparation Service.
Generates role-specific interview questions, technical deep-dives,
STAR behavioral frameworks, and project presentation coaching.
Includes circuit breaker and deterministic fallback when offline.
"""

import json
import logging
from typing import Dict, Any, List
from django.contrib.auth.models import User

from opportunities.models import Opportunity
from resumes.models import Resume
from projects.models import ProjectIdea
from services.ai_service import AIService
from services.skill_evidence_engine import SkillEvidenceEngine

logger = logging.getLogger('skillsphere.opportunities')


class InterviewPrepService:
    """
    Role-specific interview preparation coach for Opportunity Hub.
    """

    @classmethod
    def generate_prep_deck(cls, user: User, opportunity: Opportunity) -> Dict[str, Any]:
        """
        Generates role-specific interview preparation materials tailored to the
        target opportunity and student background.
        """
        required_skills = opportunity.get_required_skills_list()
        all_skills = opportunity.get_all_skills_list()

        # Fetch student resume and projects
        primary_resume = Resume.objects.filter(user=user, is_primary=True).first() or Resume.objects.filter(user=user).first()
        student_projects = list(ProjectIdea.objects.filter(user=user, status__in=['completed', 'in_progress'])[:3])

        # Prepare context for AI prompt
        prompt = (
            f"You are an expert technical interviewer and career coach. Prepare an interview practice guide for:\n"
            f"Role: {opportunity.title}\n"
            f"Organization: {opportunity.organization}\n"
            f"Opportunity Type: {opportunity.get_opportunity_type_display()}\n"
            f"Required Skills: {', '.join(required_skills) if required_skills else 'General Software Engineering'}\n"
            f"Candidate Projects: {', '.join([p.title for p in student_projects]) if student_projects else 'Personal coding exercises'}\n\n"
            f"Return a strict JSON object with this exact structure:\n"
            f"{{\n"
            f'  "technical_questions": [\n'
            f'    {{"question": "string", "key_concepts": ["string"], "recommended_approach": "string"}}\n'
            f'  ],\n'
            f'  "behavioral_questions": [\n'
            f'    {{"question": "string", "star_situation": "string", "star_action": "string", "star_result": "string"}}\n'
            f'  ],\n'
            f'  "project_talking_points": [\n'
            f'    {{"title": "string", "guidance": "string"}}\n'
            f'  ],\n'
            f'  "company_prep_tips": ["string"]\n'
            f"}}"
        )

        try:
            ai_resp = AIService.generate_text(
                prompt=prompt,
                system_instruction="You are an expert tech hiring manager. Return valid JSON only with interview preparation questions and frameworks.",
                json_mode=True,
                max_tokens=2048
            )
            if not ai_resp:
                raise ValueError("Empty response from AI")

            cleaned = ai_resp.strip()
            if "```json" in cleaned:
                cleaned = cleaned.split("```json")[1].split("```")[0].strip()
            elif "```" in cleaned:
                cleaned = cleaned.split("```")[1].split("```")[0].strip()

            deck = json.loads(cleaned)
            deck['is_ai_generated'] = True
            deck['disclaimer'] = (
                "AI Practice Simulation: These questions are generated by SkillSphere's AI Career Mentor "
                "based on the listing's required skills using the STAR framework. They are for practice and "
                "do not represent actual confidential employer assessment material."
            )
            return deck
        except Exception as e:
            logger.info(f"Using deterministic fallback interview deck for {opportunity.title}: {e}")
            return cls._get_offline_fallback_deck(opportunity, required_skills, student_projects)

    @classmethod
    def _get_offline_fallback_deck(
        cls,
        opportunity: Opportunity,
        required_skills: List[str],
        projects: List[ProjectIdea]
    ) -> Dict[str, Any]:
        """
        Deterministic, high-quality interview deck when offline or API is unavailable.
        """
        primary_skill = required_skills[0] if required_skills else 'Software Engineering'
        second_skill = required_skills[1] if len(required_skills) > 1 else 'System Design'

        technical_questions = [
            {
                "question": f"How do you handle error handling, edge cases, and performance bottlenecks when working with {primary_skill}?",
                "key_concepts": ["Exception hierarchies", "Input validation", "Time and space complexity", "Logging and observability"],
                "recommended_approach": f"Walk through a real-world scenario from your projects where {primary_skill} experienced unexpected inputs or performance lag, and describe how you profiled and resolved it."
            },
            {
                "question": f"Explain the architectural trade-offs between monolithic architectures and microservices/modular components in modern {opportunity.category} applications.",
                "key_concepts": ["Separation of concerns", "Network overhead", "Database consistency", "Deployment velocity"],
                "recommended_approach": "Contrast development simplicity with independent scalability. Emphasize starting with a clean modular structure before prematurely distributing services."
            },
            {
                "question": f"How would you design a scalable caching strategy for high-read endpoints in a {second_skill} workflow?",
                "key_concepts": ["Cache invalidation", "TTL strategies", "Redis / Memcached", "Cache-aside pattern"],
                "recommended_approach": "Detail when to read from cache, cache misses, cache-aside pattern, and how to avoid cache stampedes."
            }
        ]

        behavioral_questions = [
            {
                "question": f"Tell me about a time you faced a difficult technical challenge while building an application. How did you resolve it?",
                "star_situation": "Describe the specific project context, deadline, or bug that occurred.",
                "star_action": "Explain your systematic debugging steps, research, documentation review, and team collaboration.",
                "star_result": "Share the measurable outcome (e.g. fixed in production, 40% performance gain, learned a new pattern)."
            },
            {
                "question": f"How do you prioritize competing deadlines between coursework, projects, and new skill acquisition?",
                "star_situation": "Mention a period when multiple deadlines or project milestones converged.",
                "star_action": "Describe how you broke work into actionable milestones, communicated proactively, and used tracker tools.",
                "star_result": "Completed deliverables on time while maintaining code quality and continuous learning."
            }
        ]

        project_talking_points = []
        for p in projects:
            project_talking_points.append({
                "title": f"Presenting '{p.title}'",
                "guidance": f"Highlight your architecture choices, technologies used ({p.technologies or primary_skill}), and the user problem it solves. Be prepared to explain code trade-offs."
            })

        if not project_talking_points:
            project_talking_points.append({
                "title": "Highlighting Key Projects",
                "guidance": "Select your strongest SkillSphere portfolio project. Explain the user need, architectural decisions, and tests you wrote."
            })

        return {
            "technical_questions": technical_questions,
            "behavioral_questions": behavioral_questions,
            "project_talking_points": project_talking_points,
            "company_prep_tips": [
                f"Research {opportunity.organization}'s mission, recent public announcements, and core tech stack.",
                "Review the STAR method (Situation, Task, Action, Result) for all scenario-based questions.",
                f"Be ready to articulate your passion for {opportunity.get_opportunity_type_display()} growth."
            ],
            "is_ai_generated": False,
            "disclaimer": (
                "Verified Practice Framework: These curated questions are formulated based on industry "
                f"hiring standards and the STAR method for {opportunity.title} roles to assist your preparation."
            )
        }

    @classmethod
    def evaluate_practice_answer(
        cls,
        question: str,
        answer: str,
        opportunity: Opportunity
    ) -> Dict[str, Any]:
        """
        Evaluates a candidate's practice answer and returns structured feedback.
        """
        if not answer or len(answer.strip()) < 15:
            return {
                'score': 40,
                'feedback': "Your answer is quite brief. Try using the STAR method (Situation, Task, Action, Result) and include specific technical tools or measurable outcomes.",
                'strengths': ["Direct attempt"],
                'areas_to_improve': ["Add concrete technical examples", "Structure response with STAR format"]
            }

        prompt = (
            f"You are an encouraging but rigorous technical interview coach.\n"
            f"Target Role: {opportunity.title} at {opportunity.organization}\n"
            f"Question: {question}\n"
            f"Candidate Practice Answer: {answer}\n\n"
            f"Provide constructive critique in a strict JSON format:\n"
            f"{{\n"
            f'  "score": integer (0-100),\n'
            f'  "feedback": "string summarizing assessment",\n'
            f'  "strengths": ["string"],\n'
            f'  "areas_to_improve": ["string"]\n'
            f"}}"
        )

        try:
            resp = AIService.generate_text(
                prompt=prompt,
                system_instruction="You are an interview coach. Return valid JSON only with critique and score.",
                json_mode=True,
                max_tokens=1024
            )
            cleaned = resp.strip()
            if "```json" in cleaned:
                cleaned = cleaned.split("```json")[1].split("```")[0].strip()
            elif "```" in cleaned:
                cleaned = cleaned.split("```")[1].split("```")[0].strip()
            data = json.loads(cleaned)
            data['is_ai'] = True
            return data
        except Exception:
            # Deterministic evaluation fallback
            word_count = len(answer.split())
            score = min(88, max(50, word_count * 2))
            return {
                'score': score,
                'feedback': (
                    "Good effort! You articulated key points. To elevate this answer for interviewers at "
                    f"{opportunity.organization}, ensure you emphasize the quantifiable business or technical outcome."
                ),
                'strengths': ["Clear communication", "Relevance to question"],
                'areas_to_improve': ["Quantify impact with metrics or benchmarks", "Mention specific tools or libraries used"],
                'is_ai': False
            }
